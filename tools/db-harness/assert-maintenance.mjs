import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import pg from 'pg';
export async function assertMaintenance(c) {
  let checks=0;
  const query=async(sql,params=[]) => (await c.query(sql,params)).rows;
  const actor=async(suffix) => {await c.query('RESET ROLE'); await c.query("select set_config('request.jwt.claim.sub',$1,false)", [suffix ? `10000000-0000-0000-0000-${suffix.padStart(12,'0')}` : '']); await c.query('SET ROLE authenticated');};
  const lookup=async()=> (await query("select public.maintenance_lookup_component('LOCAL-STICKER-KEPALA-001') as v"))[0].v[0];
  const submit=async(command)=>(await query('select public.maintenance_submit($1::jsonb) as v',[JSON.stringify(command)]))[0].v;
  await actor(null);
  await assert.rejects(lookup,/unauthenticated/); checks++;
  for (const denied of ['2','5']) {await actor(denied); await assert.rejects(lookup,/forbidden/); checks++;}
  for (const allowed of ['1','3','4']) {await actor(allowed);assert.equal((await lookup()).kind,'Kepala');checks++;}
  const component=await lookup();
  const command={requestId:randomUUID(),componentId:component.id,expectedVersion:component.version,activity:'manual_check',condition:'Rusak Ringan',usable:'Tidak',impairedFunction:'Getaran',eventNote:'Pemeriksaan uji',summaryAction:'keep',summaryText:null,taskId:null,problem:null,action:null,correctsEventId:null,correctionReason:null};
  const receipt=await submit(command);
  assert.equal(receipt.componentId,component.id);checks++;
  assert.deepEqual(await submit(command),receipt);checks++;
  await assert.rejects(()=>submit({...command,eventNote:'Changed'}),/request_mismatch/);checks++;
  await assert.rejects(()=>submit({...command,requestId:randomUUID()}),/conflict/);checks++;
  await assert.rejects(()=>query('select * from public.maintenance_events'),/permission denied/);checks++;
  await c.query('RESET ROLE');
  assert.equal((await query('select status_penggunaan from public.master_komponen where id=$1',[component.id]))[0].status_penggunaan,'Tersedia');checks++;
  assert.equal(Number((await query('select count(*) from public.maintenance_events'))[0].count),1);checks++;
  await actor('3');
  const refreshed=await lookup();
  const service={...command,requestId:randomUUID(),expectedVersion:refreshed.version,activity:'service',condition:'OK',usable:'Ya',impairedFunction:'',problem:'Getaran',action:'Penyetelan',eventNote:'Hasil stabil'};
  const sr=await submit(service);assert.ok(sr.eventId);checks++;
  await c.query('RESET ROLE');
  const cost=(await query('select biaya_service,catatan from public.riwayat_service'))[0];
  assert.equal(cost.biaya_service,'0');assert.match(cost.catatan,/Biaya belum dicatat/);checks++;
  assert.equal((await query('select cost_recorded from public.maintenance_events where id=$1',[sr.eventId]))[0].cost_recorded,false);checks++;
  await c.query("create function public.test_fail_audit() returns trigger language plpgsql as $$begin raise exception 'injected audit failure'; end$$; create trigger test_fail_audit before insert on public.audit_log for each row execute function public.test_fail_audit();");
  await actor('4'); const beforeFailure=await lookup();
  await assert.rejects(()=>submit({...command,requestId:randomUUID(),expectedVersion:beforeFailure.version}),/injected audit failure/);checks++;
  assert.deepEqual(await lookup(),beforeFailure);checks++;
  await c.query('RESET ROLE');
  assert.equal(Number((await query('select count(*) from public.maintenance_events'))[0].count),2);checks++;
  await c.query('drop trigger test_fail_audit on public.audit_log; drop function public.test_fail_audit()');
  for(const [month,date] of [['2026-09-01','2026-09-26'],['2026-10-01','2026-10-24'],['2027-02-01','2027-02-27'],['2028-02-01','2028-02-26']]) {assert.equal((await query('select maintenance_private.fourth_saturday($1::date)::text as d',[month]))[0].d,date);checks++;}
  await c.query("insert into maintenance_private.settings values(true,'2026-09-01T00:00:00+07'); insert into maintenance_private.membership(component_id,code,kind,present,effective_at) select id,nomor_stiker,jenis_komponen,true,'2026-09-01T00:00:00+07' from public.master_komponen;");
  assert.equal((await query("select maintenance_private.generate_periods('2026-09-28T00:00:00+07') as n"))[0].n,1);checks++;
  assert.equal((await query("select maintenance_private.generate_periods('2026-09-28T00:00:00+07') as n"))[0].n,0);checks++;
  assert.equal(Number((await query('select count(*) from public.maintenance_tasks'))[0].count),3);checks++;
  await actor('4');
  await actor('4');
  const tasks=async(params=['2026-09',null,null,null,null,30]) => (await query('select public.maintenance_list_tasks($1,$2,$3,$4,$5,$6) as v',params))[0].v;
  const history=async(params=[component.id,null,null,null,null,30]) => (await query('select public.maintenance_list_history($1,$2,$3,$4,$5,$6) as v',params))[0].v;
  const fresh=async(extra={})=>({...command,requestId:randomUUID(),expectedVersion:(await lookup()).version,...extra});
  assert.equal((await tasks(['current',null,null,null,null,30])).period.id,(await query("select to_char(clock_timestamp() at time zone 'Asia/Jakarta','YYYY-MM') as m"))[0].m);checks++;
  for(const patch of [{condition:'Unknown'},{condition:'Rusak Berat',usable:'Ya'},{eventNote:''},{eventNote:{nested:'bad'}},{impairedFunction:[]},{correctionReason:'x'},{correctsEventId:receipt.eventId,correctionReason:'x'.repeat(2001)},{summaryAction:'clear',summaryText:'ignored'},{status_penggunaan:'Dipakai'}]) {
    await assert.rejects(()=>fresh(patch).then(submit),/invalid_input/);checks++;
  }
  await assert.rejects(()=>tasks(['2026-09',null,null,null,null,null]),/invalid_input/);checks++;
  await assert.rejects(()=>tasks(['2026-09','Wrong',null,null,null,30]),/invalid_input/);checks++;
  await assert.rejects(()=>history([null,'Wrong',null,null,null,30]),/invalid_input/);checks++;
  await assert.rejects(()=>history([null,null,null,null,'broken',30]),/invalid_input/);checks++;
  await assert.rejects(()=>history([null,null,null,null,null,null]),/invalid_input/);checks++;
  const task=(await tasks()).items.find(x=>x.componentId===component.id);
  assert.ok(task);checks++;
  await assert.rejects(()=>fresh({activity:'periodic_check',taskId:randomUUID()}).then(submit),/not_found/);checks++;
  await c.query('RESET ROLE');
  await query("update public.maintenance_periods set opens_at=clock_timestamp()+interval '1 day',closes_at=clock_timestamp()+interval '2 days' where id='2026-09'");
  await actor('4');
  await assert.rejects(()=>fresh({activity:'periodic_check',taskId:task.id}).then(submit),/task_not_open/);checks++;
  await c.query('RESET ROLE');
  await query("update public.maintenance_periods set opens_at=clock_timestamp()-interval '2 days',closes_at=clock_timestamp()-interval '1 day' where id='2026-09'");
  await actor('4');
  await assert.rejects(()=>fresh({activity:'periodic_check',taskId:task.id,condition:'Hilang'}).then(submit),/component_unavailable/);checks++;
  const periodicCommand=await fresh({activity:'periodic_check',taskId:task.id});
  const periodic=await submit(periodicCommand);
  assert.equal(periodic.completedTaskId,task.id);checks++;
  assert.deepEqual(await submit(periodicCommand),periodic);checks++;
  assert.equal((await tasks()).items.find(x=>x.id===task.id).status,'completed_late');checks++;
  await assert.rejects(()=>fresh({activity:'periodic_check',taskId:task.id}).then(submit),/task_already_completed/);checks++;
  const correction=await submit(await fresh({correctsEventId:periodic.eventId,correctionReason:'Koreksi hasil pemeriksaan'}));
  const correctionDetail=(await query('select public.maintenance_get_history($1) as v',[correction.eventId]))[0].v;
  assert.equal(correctionDetail.correctsEventId,periodic.eventId);checks++;
  const periodicDetail=(await query('select public.maintenance_get_history($1) as v',[periodic.eventId]))[0].v;
  assert.equal(periodicDetail.periodId,'2026-09');checks++;
  assert.equal(periodicDetail.legacy,false);assert.equal(periodicDetail.before.condition,'OK');checks++;
  await c.query('RESET ROLE');
  const legacyId=randomUUID();
  await query("insert into public.riwayat_checking_komponen(id,nomor_stiker,jenis_komponen,kondisi_terbaru,timestamp) values($1,$2,'Kepala','OK','2025-01-01T00:00:00Z')",[legacyId,component.code]);
  await actor('4');
  const old=(await query('select public.maintenance_get_history($1) as v',[`checking:${legacyId}`]))[0].v;
  assert.equal(old.legacy,true);assert.equal(old.before,null);assert.equal(old.identityVerified,false);checks++;
  await assert.rejects(()=>fresh({correctsEventId:old.eventId,correctionReason:'legacy'}).then(submit),/invalid_input/);checks++;
  const all=(await history()).items;
  assert.equal(all.length,5);assert.equal(new Set(all.map(x=>x.eventId)).size,5);checks++;
  const collected=[];let cursor=null;
  do {const page=await history([component.id,null,null,null,cursor,1]); collected.push(...page.items.map(x=>x.eventId));cursor=page.nextCursor;} while(cursor);
  assert.deepEqual(collected,all.map(x=>x.eventId));checks++;
  const serviceDetail=(await query('select public.maintenance_get_history($1) as v',[sr.eventId]))[0].v;
  assert.equal(serviceDetail.cost,null);assert.equal(serviceDetail.costRecorded,false);checks++;
  const taskPages=[];let taskCursor=null;
  do {const page=await tasks(['2026-09',null,null,null,taskCursor,1]);taskPages.push(...page.items.map(x=>x.id));taskCursor=page.nextCursor;}while(taskCursor);
  assert.equal(taskPages.length,3);assert.equal(new Set(taskPages).size,3);checks++;
  await c.query('RESET ROLE');
  await query("update public.riwayat_checking_komponen set catatan=' - ',fungsi_terganggu='-' where id=$1",[legacyId]);
  await actor('4');
  const normalized=(await query('select public.maintenance_get_history($1) as v',[`checking:${legacyId}`]))[0].v;
  assert.equal(normalized.note,null);assert.equal(normalized.after.impairedFunction,null);checks++;
  const otherTask=(await tasks()).items.find(x=>x.componentId!==component.id);
  const otherComponent=(await query('select public.maintenance_get_component($1) as v',[otherTask.componentId]))[0].v;
  await assert.rejects(()=>submit({...command,requestId:randomUUID(),componentId:otherComponent.id,expectedVersion:otherComponent.version,correctsEventId:receipt.eventId,correctionReason:'Wrong component'}),/invalid_input/);checks++;
  await c.query('RESET ROLE');
  await query("update public.maintenance_periods set opens_at=clock_timestamp()-interval '1 day',closes_at=clock_timestamp()+interval '1 day' where id='2026-09'");
  await actor('4');
  const onTime=await submit({...command,requestId:randomUUID(),componentId:otherComponent.id,expectedVersion:otherComponent.version,activity:'periodic_check',taskId:otherTask.id});
  assert.equal(onTime.completedTaskId,otherTask.id);assert.equal((await tasks()).items.find(x=>x.id===otherTask.id).status,'completed');checks++;
  await actor('1');
  assert.equal((await query('select public.maintenance_request_result($1) as v',[periodicCommand.requestId]))[0].v,null);checks++;
  await actor('4');
  const concurrentCommand={...command,requestId:randomUUID(),expectedVersion:(await lookup()).version};
  const cp=c.connectionParameters;
  const clients=[new pg.Client({host:cp.host,port:cp.port,user:cp.user,database:cp.database}),new pg.Client({host:cp.host,port:cp.port,user:cp.user,database:cp.database})];
  try{
    await Promise.all(clients.map(async other=>{await other.connect();await other.query("select set_config('request.jwt.claim.sub','10000000-0000-0000-0000-000000000004',false)");await other.query('SET ROLE authenticated')}));
    const values=await Promise.all(clients.map(async other=>(await other.query('select public.maintenance_submit($1::jsonb) as v',[JSON.stringify(concurrentCommand)])).rows[0].v));
    assert.deepEqual(values[0],values[1]);checks++;
  }finally{await Promise.all(clients.map(other=>other.end()));}
  await c.query('RESET ROLE');
  console.log(JSON.stringify({status:'PASS',scope:'native PostgreSQL maintenance contracts with auth shim',checks},null,2));
}
